/**
 * Сохранить недавно использованный emoji в localStorage.
 */
export function addToRecent(emoji: string): void {
  const key = 'babich_recent_emoji';
  const recent: string[] = JSON.parse(localStorage.getItem(key) || '[]');
  const filtered = recent.filter(e => e !== emoji);
  const updated = [emoji, ...filtered].slice(0, 30); // максимум 30
  localStorage.setItem(key, JSON.stringify(updated));
}

/**
 * Получить недавние emoji из localStorage.
 */
export function getRecentEmoji(): string[] {
  return JSON.parse(localStorage.getItem('babich_recent_emoji') || '[]');
}